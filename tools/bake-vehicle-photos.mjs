// Bakes the vehicle thumbnails into the hub as data-URIs.
//
//   node tools/bake-vehicle-photos.mjs [--check]
//
// Why data-URIs and not files: nothing in the hub may fetch an image. On Daniel's phone the
// Askan filter answers an unapproved image with a placeholder that looks like a success, and
// there it is the final state, not a step on the way. An inline image cannot be substituted.
//
// Reads vehicle-photos/manifest.json and the committed thumbnails beside it (made by
// tools/make-vehicle-thumbs.mjs), and writes one generated region into dist/index.html.
// --check compares without writing, for CI: the baked copy and the folder are two copies of one
// thing, and a stale bake is a red build rather than a missing picture.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const DIR = path.join(ROOT, 'vehicle-photos');
const HUB = path.join(ROOT, 'dist', 'index.html');
const CHECK = process.argv.includes('--check');

const manifest = JSON.parse(fs.readFileSync(path.join(DIR, 'manifest.json'), 'utf8'));
const photos = {}, large = {};
const webp = (p) => {
  const buf = fs.readFileSync(p);
  // Must be WEBP ("RIFF....WEBP"): anything else was not made by the thumbnail tool.
  if (buf.slice(0, 4).toString('latin1') !== 'RIFF' || buf.slice(8, 12).toString('latin1') !== 'WEBP') throw new Error('not a webp made by the tool: ' + p);
  return 'data:image/webp;base64,' + buf.toString('base64');
};
// Rows sharing a photo (the Bomber frames) read the same file once; the map still names each row.
const byFile = {};
const builds = {};
for (const e of manifest) {
  const p = path.join(DIR, e.file || '');
  // A photo of a pack HE built for this vehicle — shown under the vehicle in the large view.
  if (e.build) {
    const lp = p.replace(/\.webp$/, '.lg.webp');
    if (e.checked && fs.existsSync(lp)) builds[e.model] = webp(lp);
    continue;
  }
  if (!e.checked || !e.file || !fs.existsSync(p)) continue;
  photos[e.model] = byFile[e.file] = byFile[e.file] || webp(p);
  const lp = p.replace(/\.webp$/, '.lg.webp');
  if (!fs.existsSync(lp)) throw new Error('no large photo for ' + e.file + ' — run tools/make-vehicle-thumbs.mjs');
  const lk = e.file + '|lg';
  large[e.model] = byFile[lk] = byFile[lk] || webp(lp);
}
const js = 'const VEH_PHOTOS = ' + JSON.stringify(photos, null, 1) + ';\n'
  + '// The same photos at 480px, opened when a thumbnail is tapped.\n'
  + 'const VEH_PHOTOS_LG = ' + JSON.stringify(large, null, 1) + ';\n'
  + '// Packs he built for a vehicle, from his own photos — shown under it in the large view.\n'
  + 'const VEH_BUILD_PHOTOS = ' + JSON.stringify(builds, null, 1) + ';';
const block = '<!-- veh-photos: generated by tools/bake-vehicle-photos.mjs from vehicle-photos/ — do not edit by hand -->\n'
  + '<script>\n' + js + '\n</script>\n<!-- /veh-photos -->';

let hub = fs.readFileSync(HUB, 'utf8');
const crlf = /\r\n/.test(hub);
hub = hub.replace(/\r\n/g, '\n');
const re = /<!-- veh-photos: generated[\s\S]*?<!-- \/veh-photos -->/;
let next;
// Replacements pass a FUNCTION: a replacement string reads $& and $' as patterns.
if (re.test(hub)) next = hub.replace(re, () => block);
else {
  const anchor = '<!-- tspl: generated';
  if (!hub.includes(anchor)) throw new Error('no anchor for the photo block');
  next = hub.replace(anchor, () => block + '\n' + anchor);
}
if (CHECK) {
  const same = next === hub;
  console.log(same ? 'ok — the baked vehicle photos match vehicle-photos/' : 'STALE — dist/index.html carries different vehicle photos than vehicle-photos/');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(HUB, crlf ? next.replace(/\n/g, '\r\n') : next, 'utf8');
console.log('baked ' + Object.keys(photos).length + ' vehicle photos, ' + (js.length / 1024).toFixed(0) + 'KB');
